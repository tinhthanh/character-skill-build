#!/usr/bin/env python3
"""Build a REEL of every action of one character: a HyperFrames composition in which the character
performs each entry of tools/action-catalog.json in turn, with its name on screen — the ready-made
moves to look through (or cut from) before you put them in a scene.

    python3 tools/reel.py vet                     → reel-vet/index.html (+ character.slim.js)
    python3 tools/reel.py granny --turned         → reel-granny-turned/ (three-quarter stance)
    python3 tools/reel.py dog -o out/             → out/reel-dog/
    python3 tools/reel.py vet --only "clap,wai"   → just those actions
    python3 tools/reel.py vet --render            → also renders reel-vet/reel-vet.mp4 (HyperFrames CLI, Node)
    python3 tools/reel.py vet --clips             → renders, then cuts one clip per action: reel-vet/clips/NN-name.mp4

Every action runs through sequence(), exactly as tools/scene.py runs it. Each action gets its own
fresh character (so a stance like `carry` or `sitDown` never leaks into the next one), shown only
during its slot, with a short pause at rest before and after. Actions that need something in hand
or a pet within reach get it, as the catalog says (`items`, `pet`). The same catalog feeds
tools/actions.sh, the still review sheet.

--render / --clips need Node (npx) and, for --clips, FFmpeg. Telemetry of the HyperFrames CLI is off.
"""
import argparse, json, os, shutil, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from scene import read_timings, fail, js, html_text, slug   # noqa: E402  (dùng chung với tools/scene.py)

HYPERFRAMES = os.environ.get('HYPERFRAMES_VERSION', '0.9.52')
WIDTH, HEIGHT = 1280, 720
LEAD, TAIL = 0.5, 0.7                     # nghỉ trước / sau mỗi động tác (giây): thấy rõ dáng đầu và dáng cuối


def main():
    parser = argparse.ArgumentParser(description='Build (and optionally render) a reel of every action of one character.')
    parser.add_argument('id', help='a registered person id (vet, granny, boy …) or a pet species (dog, cat …)')
    parser.add_argument('-o', '--out', default='.', help='folder to write reel-<id>/ into (default: the current folder)')
    parser.add_argument('--turned', action='store_true', help='people: hold a three-quarter stance (facing 0.55) instead of facing front')
    parser.add_argument('--only', default='', help='comma-separated catalog labels to include')
    parser.add_argument('--render', action='store_true', help='render the reel to an mp4 with the HyperFrames CLI')
    parser.add_argument('--clips', action='store_true', help='render, then cut one mp4 per action into clips/')
    parser.add_argument('--fps', type=int, default=30)
    args = parser.parse_args()

    catalog = json.load(open(os.path.join(HERE, 'action-catalog.json'), encoding='utf-8'))
    only = [label.strip() for label in args.only.split(',') if label.strip()]
    name = f"reel-{args.id}{'-turned' if args.turned else ''}"
    out = os.path.join(os.path.abspath(args.out), name)
    os.makedirs(out, exist_ok=True)
    bundle = os.path.join(ROOT, 'dist', 'character.slim.js')
    if not os.path.isfile(bundle): fail('dist/character.slim.js is missing — run python3 tools/build.py first')
    shutil.copy(bundle, os.path.join(out, 'character.slim.js'))
    shutil.copy(os.path.join(ROOT, 'vendor', 'gsap-3.15.1.min.js'), os.path.join(out, 'gsap.min.js'))      # GSAP ghim phiên bản (đợt 27)

    # Danh mục người và thú cùng vào trang; trang tự chọn theo `id` (người hay loài thú) và lọc theo loài.
    entries = {'people': catalog['people'], 'pets': catalog['pets']}
    if only:
        known = {entry['label'] for group in entries.values() for entry in group}
        for label in only:
            if label not in known: fail(f'--only: no catalog entry "{label}" (see tools/action-catalog.json)')
        entries = {group: [entry for entry in items if entry['label'] in only] for group, items in entries.items()}

    html = f'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>{name}</title>
<!-- Generated by tools/reel.py: every action of "{html_text(args.id)}" from tools/action-catalog.json, one after another. -->
<style>
  html, body {{ margin: 0; background: #0b1218; }}
  #stage {{ position: relative; width: {WIDTH}px; height: {HEIGHT}px; overflow: hidden; background: linear-gradient(#1f4a5c, #163847 72%, #0f2a38 72%); font-family: system-ui, sans-serif; }}
  .host, .pet, .table, .label {{ position: absolute; visibility: hidden; }}
  .table {{ background: #5f7d8c; border-top: 10px solid #7d9aa8; box-sizing: border-box; }}
  .label {{ left: 40px; top: 30px; color: #e9f4f8; font-size: 34px; font-weight: 700; }}
  .label small {{ display: block; font-size: 18px; font-weight: 500; color: #9fc0cf; margin-top: 4px; }}
</style>
</head>
<body>
<div id="stage" data-composition-id="{name}" data-start="0" data-duration="__TOTAL__" data-width="{WIDTH}" data-height="{HEIGHT}">

  <script src="gsap.min.js"></script>
  <script src="character.slim.js"></script>
  <script>
    VGCharacter.seed(7);
    const id = {js(args.id)}, turned = {js(bool(args.turned))}, catalog = {json.dumps(entries, ensure_ascii=False)};
    const stage = document.getElementById('stage');
    // Thú hay người: loài thú (dog / cat) của `id`, null nếu là người. Mục chỉ dành cho một loài (`species`) thì lọc ở đây.
    const kind = VGCharacter.RigThu.LOAI[id] ? VGCharacter.RigThu.LOAI[id].loai : null, isPet = !!kind;
    const add = (cls, css) => {{ const element = document.createElement('div'); element.className = cls; element.style.cssText = css; stage.appendChild(element); return element; }};
    // Người: host cao 0,7 × khung, đứng giữa-trái; con vật "trong tầm tay" đứng trên một cái bàn bên phải người (như
    // tools/actions.html). Thú: host 0,43 × chiều cao người, giữa khung.
    const personH = {HEIGHT} * 0.7, personW = personH * 400 / 470, personX = {WIDTH} * 0.42 - personW / 2, personY = {HEIGHT} * 0.86 - personH;
    const tl = gsap.timeline({{ paused: true }});
    const slots = [];
    let at = 0.2, count = 0;
    const list = (isPet ? catalog.pets : catalog.people).filter((entry) => !entry.species || entry.species === kind);
    for (const entry of list) {{
      const parts = [];
      let rig, pet = null, scale = null, person = null;
      if (isPet) {{
        const h = personH * 0.6, w = h * 300 / 248;
        const host = add('pet', `left:${{{WIDTH} / 2 - w / 2}}px;top:${{{HEIGHT} * 0.86 - h}}px;width:${{w}}px;height:${{h}}px`);
        rig = VGCharacter.createPet(host, {{ species: id, wear: entry.wear || [] }}).rig; parts.push(host);
      }} else {{
        if (entry.pet) {{
          const w = personW * 0.5, h = personH * 0.35, left = personX + personW * 0.55, top = personY + personH * 0.46;
          const table = add('table', `left:${{left - w * 0.15}}px;top:${{top + h * 0.93}}px;width:${{w * 1.3}}px;height:${{personY + personH - top - h * 0.93}}px`);
          const petHost = add('pet', `left:${{left}}px;top:${{top}}px;width:${{w}}px;height:${{h}}px`);
          pet = VGCharacter.createPet(petHost, {{ species: entry.pet, wear: entry.wear || [] }}).rig; parts.push(table, petHost);
        }}
        const host = add('host', `left:${{personX}}px;top:${{personY}}px;width:${{personW}}px;height:${{personH}}px`);
        rig = VGCharacter.createCharacter(host, {{ id, items: entry.items || null, itemsHidden: !!entry.itemsHidden, wear: entry.wearPerson || [] }}).rig;
        if (turned && !entry.person) rig.state.facing = 0.55;
        parts.unshift(host);
        // HAI NGƯỜI (đợt 38 C): người `entry.person` đứng bên phải, cách tâm `personGap` (đơn vị ô 235 px của bản duyệt), cỡ `personScale`.
        if (entry.person) {{
          const h = personH * (entry.personScale || 1), w = h * 400 / 470, cx = personX + personW / 2 + (entry.personGap || 84) * personH / 235;
          const personHost = add('host', `left:${{cx - w / 2}}px;top:${{personY + personH - h}}px;width:${{w}}px;height:${{h}}px`);
          person = VGCharacter.createCharacter(personHost, {{ id: entry.person, items: entry.personItems || null, itemsHidden: !!entry.personItemsHidden }}).rig; parts.push(personHost);
        }}
        // "scale" (đợt 35, `weigh`): một cái cân trên sàn bên trái người — `@scale` trong các bước.
        if (entry.scale) {{
          const scaleHost = add('scale', `left:${{personX - personW * 0.31}}px;top:${{personY}}px;width:${{personW}}px;height:${{personH}}px`);
          host.parentNode.insertBefore(scaleHost, host);
          scale = VGCharacter.createProp(scaleHost, 'scale', {{ reading: entry.scale === true ? '4.2 kg' : String(entry.scale) }}); parts.push(scaleHost);
        }}
      }}
      const label = add('label', '');
      count++;
      label.innerHTML = `${{String(count).padStart(2, '0')}} · ${{entry.label.replace(/</g, '&lt;')}}<small>${{id}}${{turned ? ' · turned 3/4' : ''}}</small>`;
      parts.push(label);
      const steps = entry.steps.map((step) => (Array.isArray(step) ? step.map((arg) => (arg === '@pet' ? pet : arg === '@scale' ? scale : arg === '@person' ? person : arg)) : step));
      // ĐỢT 39 C: chụp ảnh tự sướng cùng ai — `{{ "with": "@person" }}` (hay "@pet") trong tuỳ chọn của bước.
      for (const step of steps) if (Array.isArray(step)) step.forEach((arg, n) => {{ if (arg && typeof arg === 'object' && !arg.svg && (arg.with === '@person' || arg.with === '@pet')) step[n] = {{ ...arg, with: arg.with === '@pet' ? pet : person }}; }});
      const line = VGCharacter.sequence(rig, steps);
      if (person && entry.personSteps) tl.add(VGCharacter.sequence(person, entry.personSteps.map((step) => (Array.isArray(step) ? step.map((arg) => (arg === '@self' || arg === '@pet' ? rig : arg)) : step))).paused(false), at + {LEAD});
      const start = at, end = at + {LEAD} + line.duration() + {TAIL};
      // Chỉ hiện trong khung giờ của mình. `visibility` bằng set của timeline: tua tới / tua lui đều đúng.
      tl.set(parts, {{ visibility: 'visible' }}, start).set(parts, {{ visibility: 'hidden' }}, end);
      tl.add(line.paused(false), start + {LEAD});
      slots.push([start, end, entry.label]);
      at = end;
    }}
    window.__timelines = window.__timelines || {{}};
    window.__timelines[{js(name)}] = tl;
    // Read by tools/reel.py (the total length and where each action is, to cut clips).
    window.__sceneTimings = {{ duration: Math.max(tl.duration(), at), turns: slots, speech: [] }};
  </script>
</div>
</body>
</html>
'''
    target = os.path.join(out, 'index.html')
    open(target, 'w', encoding='utf-8').write(html.replace('__TOTAL__', '600'))
    timings = read_timings(out, target)
    total = round(timings['duration'] + 0.2, 2)
    open(target, 'w', encoding='utf-8').write(html.replace('__TOTAL__', f'{total:g}'))
    slots = timings['turns']
    if not slots: fail(f'no catalog entry fits "{args.id}"')
    print(target)
    print(f'  {len(slots)} actions, {total:g} s')

    if not (args.render or args.clips): return
    env = dict(os.environ, HYPERFRAMES_NO_TELEMETRY='1', DO_NOT_TRACK='1')
    movie = os.path.join(out, f'{name}.mp4')
    if shutil.which('npx') is None: fail('npx not found — install Node to render')
    done = subprocess.run(['npx', '--yes', f'hyperframes@{HYPERFRAMES}', 'render', '--fps', str(args.fps), '-o', movie, '.'], cwd=out, env=env)
    if done.returncode != 0 or not os.path.isfile(movie): fail('the render failed (see the HyperFrames output above)')
    print(movie)
    if not args.clips: return
    if shutil.which('ffmpeg') is None: fail('ffmpeg not found — needed to cut the clips')
    folder = os.path.join(out, 'clips')
    os.makedirs(folder, exist_ok=True)
    for number, (start, end, label) in enumerate(slots, 1):
        clip = os.path.join(folder, f'{number:02d}-{slug(label) or "action"}.mp4')
        # Cắt có mã hoá lại: cắt theo keyframe thì clip bắt đầu lệch giờ.
        cut = subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-ss', f'{start:.3f}', '-to', f'{end:.3f}', '-i', movie,
                              '-c:v', 'libx264', '-crf', '18', '-pix_fmt', 'yuv420p', '-an', clip])
        if cut.returncode != 0: fail(f'ffmpeg could not cut {label}')
    print(f'  {len(slots)} clips in {folder}')


if __name__ == '__main__':
    main()
